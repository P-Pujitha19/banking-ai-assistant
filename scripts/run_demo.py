#!/usr/bin/env python
"""Run the 15 demonstration conversations and write docs/SAMPLE_CONVERSATIONS.md from REAL outputs.

    python scripts/run_demo.py
"""
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from banking_ai.agents.orchestrator import BankingAssistant  # noqa: E402
from banking_ai.config.logging_config import configure_logging  # noqa: E402
from banking_ai.config.settings import get_settings  # noqa: E402

DEMOS = [
    ("1. Balance inquiry", "CUST1001", ["What is my account balance?"]),
    ("2. Transaction history", "CUST1001", ["Show my last 5 transactions"]),
    ("3. Recent transaction", "CUST1001", ["What was my last transaction?"]),
    ("4. Loan eligibility", "CUST1001", ["Can I get a personal loan of 5 lakh for 5 years?"]),
    ("5. Loan interest rate", "CUST1001", ["What is the interest rate for a personal loan?"]),
    ("6. EMI calculation", "CUST1001", ["Calculate EMI for 5 lakh for 5 years at 10%"]),
    ("7. Account charges", "CUST1001", ["What are the charges for my account?"]),
    ("8. Minimum balance (RAG)", "CUST1001", ["What is the minimum balance for a savings account?"]),
    ("9. Loan comparison", "CUST1001", ["Compare personal loan and home loan"]),
    ("10. Transaction explanation", "CUST1002", ["Why was money deducted from my account?"]),
    ("11. Multi-turn conversation", "CUST1001", ["I want a personal loan.", "I need 5 lakh.", "What about 7 years?", "Calculate the EMI at 10%"]),
    ("12. Ambiguous query", "CUST1001", ["calculate my emi", "5 lakh", "for 5 years"]),
    ("13. Unknown query", "CUST1001", ["What's the weather like in Mumbai?"]),
    ("14. Greeting", "CUST1001", ["Hello!"]),
    ("15. Complex banking query", "CUST1001", ["I earn 90k per month, can I get a home loan of 30 lakh for 20 years?", "What if I choose 25 years instead?"]),
]


def main() -> None:
    settings = get_settings().with_overrides(bank_api_mode="inprocess", log_file=None, log_level="ERROR")
    configure_logging("ERROR", None)
    assistant = BankingAssistant.from_settings(settings)
    lines = ["# Sample Conversations", "",
             f"_Generated by `scripts/run_demo.py` on {datetime.now():%Y-%m-%d %H:%M} in **{assistant.mode}** mode "
             f"(intent backend: `{assistant.classifier.backend.name}`, vector store: `{assistant.rag.backend}`). "
             "All data is synthetic. These are real outputs of the code, not hand-written examples._", ""]
    for title, customer, turns in DEMOS:
        lines += [f"## {title}", f"_Customer: `{customer}`_", ""]
        session = None
        for text in turns:
            reply = assistant.handle(customer, text, session)
            session = reply.session_id
            tools = ", ".join(t["tool"] for t in reply.tools) or "none"
            lines += [f"**User:** {text}", "", f"**Assistant:**", "", *[f"> {ln}" if ln else ">" for ln in reply.response.splitlines()], "",
                      f"<sub>intent `{reply.intent}` ({reply.confidence:.2f}) · tools: {tools} · sources: {', '.join(reply.sources) or 'none'} · "
                      f"status: {reply.status} · {reply.latency_ms:.0f} ms</sub>", ""]
    out = ROOT / "docs" / "SAMPLE_CONVERSATIONS.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
